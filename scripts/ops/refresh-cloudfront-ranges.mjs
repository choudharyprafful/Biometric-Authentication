// Regenerates artifacts/api-server/src/lib/cloudfrontRanges.ts from AWS's published IP ranges.
// Run when AWS adds CloudFront ranges: node scripts/ops/refresh-cloudfront-ranges.mjs
import fs from "node:fs";

const res = await fetch("https://ip-ranges.amazonaws.com/ip-ranges.json");
if (!res.ok) throw new Error(`ip-ranges.json: HTTP ${res.status}`);
const data = await res.json();

const services = new Set(["CLOUDFRONT", "CLOUDFRONT_ORIGIN_FACING"]);
const v4 = data.prefixes.filter((p) => services.has(p.service)).map((p) => p.ip_prefix);
const v6 = data.ipv6_prefixes.filter((p) => services.has(p.service)).map((p) => p.ipv6_prefix);
const ranges = [...new Set([...v4, ...v6])].sort();
if (ranges.length < 100) throw new Error(`only ${ranges.length} CloudFront ranges found — refusing to write a list that small`);

const out = new URL("../../artifacts/api-server/src/lib/cloudfrontRanges.ts", import.meta.url);
fs.writeFileSync(
  out,
  `// Generated by scripts/ops/refresh-cloudfront-ranges.mjs from https://ip-ranges.amazonaws.com/ip-ranges.json
// (services CLOUDFRONT and CLOUDFRONT_ORIGIN_FACING, syncToken ${data.syncToken}, ${data.createDate}). Do not edit by hand.
export const CLOUDFRONT_RANGES: readonly string[] = ${JSON.stringify(ranges, null, 2)};\n`,
);
console.log(`wrote ${ranges.length} CloudFront ranges (syncToken ${data.syncToken})`);
